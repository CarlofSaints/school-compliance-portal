// Rewrites lib/campusLibrary/index.ts from the JSON files beside it, in the
// order Carl asked for (BELA, finances, Schools Act, GDE). Run after adding one:
//   node scripts/build-campus-library-index.mjs
import { readdirSync, writeFileSync } from "node:fs";

const dir = "lib/campusLibrary";
const ORDER = ["bela-", "finance-", "sasa-", "gde-"];
const rank = (f) => {
  const i = ORDER.findIndex((p) => f.startsWith(p));
  return i < 0 ? ORDER.length : i;
};
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".json"))
  .sort((a, b) => rank(a) - rank(b) || a.localeCompare(b));
const ident = (f) => f.replace(".json", "").replace(/-(\w)/g, (_, c) => c.toUpperCase());
writeFileSync(
  `${dir}/index.ts`,
  `// The built-in course library: one JSON file per module. GENERATED by
// scripts/build-campus-library-index.mjs, do not edit by hand.
// Checked by scripts/check-campus-library.ts.
import type { LibraryCourse } from "../campusLibraryTypes";
${files.map((f) => `import ${ident(f)} from "./${f}";`).join("\n")}

export const LIBRARY = [
${files.map((f) => `  ${ident(f)},`).join("\n")}
] as LibraryCourse[];
`
);
console.log(`${files.length} courses indexed`);
